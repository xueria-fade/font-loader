val modReadableName = providers.gradleProperty("modReadableName").get()
val modName = providers.gradleProperty("modName").get()
val modVersion = providers.gradleProperty("modVersion").get()

plugins {
    alias(libs.plugins.fish.loom)
    alias(libs.plugins.setup.mite)
}

version = modVersion

base {
    archivesName = modName
}

repositories {
    mavenCentral()
    maven("https://maven.limingzxc.top/repository/maven-public/")
}

val loader = configurations.create("loader") {
    configurations.implementation.get().extendsFrom(this)
}

dependencies {
    minecraft("com.mojang:minecraft:1.6.4-MITE")

    // Add fish mod loader dependency
    "loader"("com.github.MinecraftIsTooEasy:FishModLoader:3.4.2")
}

loom {
    accessWidenerPath = layout.projectDirectory
        .dir("src")
        .dir("main")
        .dir("resources")
        .file("$modName.accesswidener")

    mergedMinecraftJar()

    fml = loader.singleFile

    // Add the mappings generated by FML to the mappings configuration
    project.dependencies.add("mappings", fmlMCPMappings())

    mods {
        create(modName) {
            sourceSet(sourceSets.main.get())
        }
    }
}

tasks.processResources {
    // for code completion
    rename("fabric.mod.json", "fml.mod.json")

    val properties = mapOf(
        "id" to modName,
        "name" to modReadableName,
        "version" to modVersion
    )

    inputs.properties(properties)

    filesMatching("fabric.mod.json") {
        expand(properties)
    }
}

java {
    withSourcesJar()

    toolchain {
        languageVersion.set(JavaLanguageVersion.of(17))
    }
}